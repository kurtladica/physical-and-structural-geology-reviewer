import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import { tutorPlugin } from './server/tutor'

/** Files in `public/` that the offline shell needs even before a page is rendered. */
const SHELL_FILES = [
  '/',
  '/index.html',
  '/manifest.webmanifest',
  '/icons/icon.svg',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon-maskable-512.png',
  '/icons/apple-touch-icon.png',
]

function hash(value: string) {
  let h = 5381
  for (let i = 0; i < value.length; i += 1) h = ((h << 5) + h + value.charCodeAt(i)) >>> 0
  return h.toString(36)
}

/**
 * Emits `sw.js` after the bundle is written, precaching every hashed asset so the
 * built site works with no network at all. The cache name is derived from the file
 * list, so every new build installs a fresh cache and drops the previous one.
 */
function offlineShell(): Plugin {
  return {
    name: 'geostud-offline-shell',
    apply: 'build',
    generateBundle(_options, bundle) {
      const precache = new Set(SHELL_FILES)
      for (const fileName of Object.keys(bundle)) {
        if (fileName === 'index.html') continue
        if (/\.(woff|ttf)$/i.test(fileName)) continue // woff2 covers every modern browser
        precache.add('/' + fileName)
      }
      const files = [...precache].sort()
      // Public assets keep stable URLs, so hash their contents too. Without this a
      // re-deployed icon or manifest would stay stale inside an installed app.
      const publicContents = SHELL_FILES.map((file) => {
        if (file === '/' || file === '/index.html') return ''
        try {
          return readFileSync(resolve(process.cwd(), 'public', file.slice(1)), 'utf8')
        } catch {
          return ''
        }
      }).join('|')
      const cacheName = `geostud-${hash(files.join('|') + publicContents)}`

      const source = `/* Generated by the GeoStud build — do not edit by hand. */
const CACHE = ${JSON.stringify(cacheName)}
const PRECACHE = ${JSON.stringify(files, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE)
      await cache.addAll(PRECACHE.map((url) => new Request(url, { cache: 'reload' })))
      await self.skipWaiting()
    })(),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys()
      await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))
      await self.clients.claim()
    })(),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  // The AI tutor needs a live server; leave it alone so it fails honestly offline.
  if (url.pathname.startsWith('/api/')) return

  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const cache = await caches.open(CACHE)
        const cached = await cache.match('/index.html')
        if (cached) {
          event.waitUntil(
            fetch(request)
              .then((response) => (response.ok ? cache.put('/index.html', response.clone()) : undefined))
              .catch(() => undefined),
          )
          return cached
        }
        try {
          return await fetch(request)
        } catch {
          return new Response(
            '<!doctype html><meta charset="utf-8"><title>Offline</title><p>GeoStud has not been saved for offline use yet. Open it once with a connection, then try again.',
            { headers: { 'content-type': 'text/html; charset=utf-8' }, status: 503 },
          )
        }
      })(),
    )
    return
  }

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE)
      const cached = await cache.match(request)
      if (cached) return cached
      try {
        const response = await fetch(request)
        if (response.ok && response.type === 'basic') await cache.put(request, response.clone())
        return response
      } catch {
        return new Response('', { status: 504, statusText: 'Offline' })
      }
    })(),
  )
})
`

      this.emitFile({ type: 'asset', fileName: 'sw.js', source })
    },
  }
}

export default defineConfig({
  plugins: [react(), tutorPlugin(), offlineShell()],
  server: {
    host: '0.0.0.0',
    port: 3000,
  },
})
